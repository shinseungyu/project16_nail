// ===========================================================================
//  완성 프롬프트 (project15 rewrite-prompt.ts 의 한국 네일 창업판) — 순수 함수, 화면에서 바로 조립
//  - 출력 형식을 "정해진 틀"(사이트 템플릿 계약)에 고정해서, 붙여넣으면 그대로 요약 박스·목차·FAQ 가 된다.
//  - 애드센스 승인 사이트라 수익 보장·과장·날조·광고 클릭 유도를 특히 강하게 막는다.
// ===========================================================================
import type { AnalysisSummary, InternalLink } from './types'
import { CATEGORY_KEYS, ALLOWED_EXTERNAL_HOSTS } from '@site/lib/blog/config'

export interface PromptInput {
  keyword: string
  summary: AnalysisSummary | null
  links: InternalLink[]
  /** 사람이 직접 확인한 사실(선택) */
  facts?: string
}

function survey(s: AnalysisSummary | null): string {
  if (!s) return '（상위글 분석 없음 — 검색 의도를 스스로 판단해 작성）'
  const list = (a: string[]) => (a.length ? a.join(' / ') : '(없음)')
  return [
    `- 상위글 실제 제목(표현 참고만, 복제 금지):${s.topTitles.length ? '\n' + s.topTitles.map((t) => `    · ${t}`).join('\n') : ' (없음)'}`,
    `- 제목 패턴: ${s.titlePattern}`,
    `- 자주 나온 소제목: ${list(s.commonHeadings)}`,
    `- 평균 본문 분량(공백 제외): ${s.avgLength.toLocaleString()}자`,
    `- 숫자 리스트 표현: ${list(s.numberLists)}`,
    `- 자주 나온 단어: ${s.topKeywords.slice(0, 15).map((k) => k.word).join(', ') || '(없음)'}`,
    `- 상위글이 비교하는 대상: ${list(s.comparisonTargets)}`,
    `- 상위글 FAQ 질문(질문만 참고, 답은 새로 작성): ${list(s.faqQuestions.slice(0, 10))}`,
    `- 다루는 주제 묶음: ${list(s.faqThemes)}`,
    `- 구조화 데이터: ${s.schemaSummary}`,
  ].join('\n')
}

export function buildPrompt({ keyword, summary, links, facts }: PromptInput): string {
  const avg = summary?.avgLength ?? 0
  const target = avg > 0 ? Math.min(6000, Math.max(2500, avg)) : 3500
  const linkList = links.map((l) => `- [${l.label}](${l.href})`).join('\n')
  const officialHosts = Array.from(new Set(ALLOWED_EXTERNAL_HOSTS.map((h) => h.replace(/^www\./, '')))).join(', ')

  return `당신은 네일·뷰티 창업 정보 사이트(nailstartup.com) "네일샵 창업"의 편집자입니다.
아래 자료를 바탕으로 [키워드]에 대한 한국어 블로그 글을 새로 작성하세요.
상위글은 구조·논점·검색 의도만 참고하고, 문장은 절대 복제하거나 말만 바꿔 옮기지 않습니다.

# 키워드
${keyword}

# 상위글 데이터 (구조·패턴만 참고, 복제 금지)
${survey(summary)}

# 사이트 기준 정보 (이 범위와 모순되는 수치를 쓰지 말 것)
- 1인 네일샵 창업비용: 약 800만~2,000만 원 범위(사이트 대표 예시 1,480만 원). 지역·규모·인테리어 수준에 따라 달라진다고 함께 밝힌다.
- 1인 네일샵 월 순수익: 약 250만~350만 원 범위(운영이 안정된 경우의 예시). 초기에는 더 낮을 수 있다고 밝힌다.
- 네일 영업에는 미용사(네일) 국가기술자격과 미용업 영업신고가 필요하다. 세부 요건·절차는 큐넷·관할 구청 기준으로 확인하도록 안내한다.

# 직접 확인한 사실 (있으면 우선 반영 — 없으면 일반적인 범위로만 쓴다)
${facts?.trim() ? facts.trim() : '(없음)'}

# 내부 링크 (이 목록에 있는 주소만 사용 — 목록 밖 주소를 만들지 말 것)
${linkList || '(없음)'}

# 핵심 원칙 (반드시 지킬 것)
1. 복제 금지: 상위글 문장을 3어절 이상 그대로 쓰지 않는다. 모든 문장을 새로 쓴다.
2. 수익·성공 보장 금지: "수익 보장", "무조건 성공", "누구나 월 ○○만 원" 같은 표현을 쓰지 않는다. 수치는 항상 범위 + 조건(지역·규모·운영 방식)으로 쓴다.
3. 과장 금지: "최고", "1위", "유일한", "완벽한", "압도적" 같은 최상급·단정 표현을 쓰지 않는다.
4. 날조 금지: 통계·조사 결과·논문·기사·URL·인용을 지어내지 않는다. 출처는 실제 존재하는 공공기관명(한국산업인력공단 큐넷, 관할 시·군·구청 위생과, 국세청 홈택스, 소상공인시장진흥공단 등)만 쓴다. 확실하지 않은 수치는 쓰지 않는다.
5. 경험담 날조 금지: "제가 직접 운영해 보니", "저희 샵에서는" 처럼 겪지 않은 경험을 쓰지 않는다. 이 사이트는 정보 사이트다.
6. 광고 관련 문구 금지: "광고를 클릭", "아래 배너" 등 광고를 언급하거나 클릭을 유도하는 문장을 쓰지 않는다(애드센스 정책 위반).
7. 의료 표현 금지: 손발톱 질환·피부 문제를 "치료·완치·처방"으로 표현하지 않는다. 의학적 판단이 필요한 내용은 "전문의 상담을 권한다"로 안내한다.
8. 외부 링크는 공공기관(${officialHosts})만, 그 외 외부 링크는 넣지 않는다.

# 정해진 틀 (이 구조 그대로 — 사이트 템플릿이 자동으로 요약 박스·목차·FAQ 로 바꾼다)
\`\`\`
# 제목

## 핵심 요약
- (1줄째: 검색한 사람이 가장 알고 싶은 것에 대한 결론을 한 문장으로)
- (요점 2~4개, 각 한 문장. 숫자가 있으면 숫자로)

(도입 문단 2~3문장: 누구를 위한 글이고 무엇을 알 수 있는지)

## (본문 소제목 1 — 검색 의도에 대한 답을 가장 먼저)
### (필요하면 세부 소제목)
(본문)

## (본문 소제목 2~6)
...

## 자주 묻는 질문
### (질문 1?)
(답변 2~4문장)
### (질문 2?)
(답변)
(3~5개)

## 마치며
(핵심 정리 2~3문장 + 다음에 볼 내부 링크 1개)
\`\`\`
- "## 핵심 요약", "## 자주 묻는 질문", "## 마치며" 세 소제목은 글자 그대로 쓴다.
- 목차는 쓰지 않는다(사이트가 자동 생성). 작성자·감수 표기, 면책 문구도 쓰지 않는다(사이트가 자동으로 붙인다).
- 본문 소제목(##)은 4~7개. 각 소제목 아래 최소 3~4문장. 1~2문장으로 넘기지 않는다.
- 비용·비교·절차 정보는 마크다운 표로 정리한다(헤더 줄 + |---| 구분 줄, 한 줄에 한 행).
- 꼭 기억할 내용은 "> " 인용 줄로 1~2곳 강조한다(사이트에서 체크 포인트 박스로 보인다).
- 숫자 리스트형 소제목("○가지", "○단계")을 1~2개 쓴다${summary?.numberLists.length ? `(상위글 예: ${summary.numberLists.join(', ')})` : ''}.
- 내부 링크는 위 목록에서 2~4개를 본문 문장 안에 자연스럽게 [앵커 텍스트](/주소) 형식으로 넣는다. 앵커는 "여기"가 아니라 내용이 드러나는 말로.
- 이미지는 만들지 않는다. 이미지가 있으면 좋을 자리에 단독 줄로 [이미지: 설명] 표시만 1~3개 둔다(사람이 나중에 넣는다).

# 검색 의도 충족 (가장 중요)
1. 키워드에서 "이 사람이 진짜 알고 싶은 한 가지"를 먼저 정한다. (예: "네일샵 창업비용" → 총 얼마가 드는지와 항목별 내역 / "네일 자격증 독학" → 혼자 붙을 수 있는지와 준비 기간)
2. 핵심 요약 첫 줄과 첫 번째 본문 소제목에서 그 질문에 결론부터 답한다. 결론을 뒤로 미루지 않는다.
3. 각 소제목도 "결론 → 이유 → 예시·주의점" 순서로 쓴다.
4. "무엇"뿐 아니라 "왜 그런지", "어떤 경우에는 달라지는지", "어떤 사람에게는 맞지 않는지"까지 쓴다.
5. 상위글이 비교하는 대상이 있으면 "○○와 △△ 차이" 소제목과 비교표를 넣는다.

# 분량
- 목표: 공백 제외 약 ${target.toLocaleString()}자(상위글 평균 ${avg ? avg.toLocaleString() + '자' : '정보 없음'} 기준 ±20%).
- 분량을 채우려고 같은 말을 반복하거나 일반론을 늘어놓지 않는다. 쓸 내용을 다 쓰면 거기서 끝낸다.

# 문체·표기
- "~합니다/~입니다" 존댓말. 확실한 사실은 단정하고, 상황에 따라 다른 것은 "~인 경우가 많습니다", "~에 따라 달라집니다"로 쓴다.
- 금액은 "800만~2,000만 원", 기간은 "2~3개월"처럼 아라비아 숫자와 쉼표를 쓴다. 연도가 필요하면 2026년 기준으로 쓴다.
- 같은 대상을 글 안에서 다른 이름으로 부르지 않는다(예: "1인샵"과 "1인 네일샵"을 섞지 않기).
- 키워드는 제목 앞쪽, 핵심 요약 첫 줄, 첫 문단, 소제목의 절반 정도에 자연스럽게 넣는다. 억지로 반복하지 않는다.

# 제목
1. 상위글 제목에 반복되는 요소(비용·기간·방법·비교 등)를 세어 본다.
2. 많이 겹치는 요소는 넣고, 상위글이 놓친 요소는 차별점으로 검토한다.
3. 제목 후보 3개를 만들고 각각 이유를 한 줄로 단 뒤, 가장 맞는 1개를 고른다.
- 키워드는 제목 앞쪽에. 공백 포함 32자 이내 권장. 상위글 제목 표현을 그대로 쓰지 않는다.

# 메타 정보
- description: 80~150자. 키워드로 시작 → 검색 의도에 대한 답을 한 마디 → 이 글에만 있는 구체적인 내용 1개 → 읽을 이유. "~에 대해 알아보겠습니다" 같은 빈 문장 금지.
- slug: 영어 소문자와 하이픈 3~6단어 (예: nail-shop-startup-cost)
- category: ${CATEGORY_KEYS.join(' / ')} 중 하나
- tags: 3~5개

# 출력 형식 (이 순서 그대로)
1) 본문 — "# 제목"부터 "## 마치며"까지 위의 정해진 틀대로
2) 그 다음 줄에 ===META=== 를 쓰고 아래 형식으로:
title: (최종 제목)
description: (설명)
slug: (영문 주소)
category: (카테고리)
tags: (태그1, 태그2, 태그3)
title_candidates:
1. (후보) ← (이유)
2. (후보) ← (이유)
3. (후보) ← (이유)
3) 그 다음 줄에 ===CHECK=== 를 쓰고 자기 점검을 한 줄씩:
- [ ] 핵심 요약 첫 줄이 검색 의도에 대한 결론이다
- [ ] 첫 번째 본문 소제목이 검색 의도에 바로 답한다
- [ ] 수익·성공 보장, 과장 표현이 없다
- [ ] 지어낸 통계·출처·경험담이 없다
- [ ] 상위글 문장을 복제하지 않았다
- [ ] 수치는 범위 + 조건으로 썼고 사이트 기준 정보와 충돌하지 않는다
- [ ] 표 1개 이상, 내부 링크 2~4개(목록 안 주소만)
- [ ] 자주 묻는 질문 3~5개, "## 마치며"로 끝난다
- [ ] 분량을 채우려는 반복이 없다

지금 [키워드]로 작성하세요.`
}
